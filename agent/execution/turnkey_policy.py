"""Turnkey policy that mirrors the employee's whitelist in the signing layer.

Even if this app were compromised, Turnkey would only sign a USDT transfer() to a
whitelisted address on the configured chain. Amount caps are not enforced here
(Turnkey reads raw calldata), so the employee wallet should only hold the small budget.
"""

from __future__ import annotations

import json
from typing import Iterable

TRANSFER_SELECTOR = "0xa9059cbb"


def condition(chain_id: int, token_address: str, payees: Iterable[str]) -> str:
    payees = sorted({p.lower().removeprefix("0x") for p in payees})
    if not payees:
        raise ValueError("白名单是空的，Turnkey 策略会拒绝所有付款")
    # transfer(address,uint256) calldata: "0x" + 8-char selector + 24 zero chars + 40-char address
    to_payee = " || ".join(f"eth.tx.data[34..74] == '{p}'" for p in payees)
    return (
        f"eth.tx.chain_id == {chain_id}"
        f" && eth.tx.to == '{token_address.lower()}'"
        " && eth.tx.value == 0"
        f" && eth.tx.data[0..10] == '{TRANSFER_SELECTOR}'"
        f" && ({to_payee})"
    )


def policy(chain_id: int, token_address: str, payees: Iterable[str], api_user_id: str) -> dict:
    return {
        "policyName": "ChainStaff: USDT to whitelist only",
        "effect": "EFFECT_ALLOW",
        "consensus": f"approvers.any(user, user.id == '{api_user_id}')",
        "condition": condition(chain_id, token_address, payees),
        "notes": "Generated by scripts/turnkey_policy.py from config/policy.json",
    }


def policy_json(chain_id: int, token_address: str, payees: Iterable[str], api_user_id: str) -> str:
    return json.dumps(policy(chain_id, token_address, payees, api_user_id), indent=2, ensure_ascii=False)
